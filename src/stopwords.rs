#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn stopwords_match_nagisa_030() {
        let reference: serde_json::Value =
            serde_json::from_str(include_str!("../tests/fixtures/compat_030.json")).unwrap();
        let expected: Vec<_> = reference["stopwords"]
            .as_array()
            .unwrap()
            .iter()
            .map(|word| word.as_str().unwrap())
            .collect();
        assert_eq!(STOPWORDS, expected);
    }
}
